/** Occasion keys, for membership checks. */
const SPECIAL_DATES = new Set(SPECIAL_DATE_KEYS);

/** Ordinary lines, in calendar order. */
const GENERIC_QUOTES: readonly string[] = Object.keys(NOT_FOUND_QUOTES_BY_DATE)
  .filter((key) => !SPECIAL_DATES.has(key))
  .map((key) => NOT_FOUND_QUOTES_BY_DATE[key]);

/** Visit memory so a refresh counts as another landing on the same day. */
const MISSING_PAGE_VISIT_KEY = 'portfolio-v2-missing-page-quote';

/** How many times the missing page has been opened on one ordinary day. */
interface MissingPageVisit {
  dateKey: string;
  visitIndex: number;
}

/**
 * Format a local date as `MM-DD`.
 * @param date Local date.
 * @returns Month and day key used by the quote map.
 */
function dateKey(date: Date): string {
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  return `${month}-${day}`;
}

/**
 * Report whether a date owns an occasion line.
 * @param date Local date.
 * @returns True when that day's line never enters the rotation.
 */
export function isSpecialDate(date: Date): boolean {
  return SPECIAL_DATES.has(dateKey(date));
}

/**
 * Pick the missing-page line for a visitor's local calendar day.
 * February 29 is included and is reached only when that date exists.
 * @param date Local date used to choose the line.
 * @returns The line for that month and day.
 */
export function quoteForLocalDate(date: Date): string {
  return NOT_FOUND_QUOTES_BY_DATE[dateKey(date)] ?? NOT_FOUND_QUOTES_BY_DATE['01-01'];
}

/**
 * Narrow stored JSON to a visit record.
 * @param value Parsed storage value.
 * @returns True when the value has a date key and a visit number.
 */
function isMissingPageVisit(value: unknown): value is MissingPageVisit {
  if (typeof value !== 'object' || value === null) {
    return false;
  }
  const record = value as MissingPageVisit;
  return typeof record.dateKey === 'string' && typeof record.visitIndex === 'number';
}

/**
 * Read how many landings have already happened today.
 * @param storage Visit memory.
 * @param key Today's `MM-DD` key.
 * @returns The visit number for this landing, starting at 0.
 */
function readVisitIndex(storage: Storage, key: string): number {
  try {
    const raw = storage.getItem(MISSING_PAGE_VISIT_KEY);
    if (raw === null) {
      return 0;
    }
    const parsed: unknown = JSON.parse(raw);
    if (!isMissingPageVisit(parsed) || parsed.dateKey !== key) {
      return 0;
    }
    return parsed.visitIndex + 1;
  } catch {
    return 0;
  }
}

/**
 * Remember this landing so the next one can rotate.
 * @param storage Visit memory.
 * @param key Today's `MM-DD` key.
 * @param visitIndex Visit number just shown.
 */
function writeVisitIndex(storage: Storage, key: string, visitIndex: number): void {
  try {
    const state: MissingPageVisit = {
      dateKey: key,
      visitIndex,
    };
    storage.setItem(MISSING_PAGE_VISIT_KEY, JSON.stringify(state));
  } catch {
    // A blocked storage API still leaves the chosen line on screen.
  }
}

/**
 * Pick the line for one landing, rotating only on ordinary days.
 * Visit 0 is that day's line. Later visits walk forward through
 * ordinary lines and wrap after December.
 * An occasion day ignores the visit number and always returns its own line.
 * @param date Local date used to choose the line.
 * @param visitIndex How many earlier landings happened on this same ordinary day.
 * @returns The line for this landing.
 */
export function quoteForRepeatVisit(date: Date, visitIndex: number): string {
  const today = quoteForLocalDate(date);
  if (isSpecialDate(date) || visitIndex <= 0) {
    return today;
  }
  const start = GENERIC_QUOTES.indexOf(today);
  const origin = start === -1
    ? 0
    : start;
  return GENERIC_QUOTES[(origin + visitIndex) % GENERIC_QUOTES.length];
}

/**
 * Choose the line for this landing and remember it for the next one.
 * The first landing on an ordinary day uses that day's line.
 * Later landings rotate through ordinary lines.
 * An occasion line stays on its own day.
 * @param date Local date for this landing.
 * @param storage Visit memory. Defaults to localStorage so a refresh counts as another landing.
 * @returns The line to show.
 */
export function quoteForLanding(date: Date, storage: Storage = localStorage): string {
  if (isSpecialDate(date)) {
    return quoteForLocalDate(date);
  }
  const key = dateKey(date);
  const visitIndex = readVisitIndex(storage, key);
  writeVisitIndex(storage, key, visitIndex);
  return quoteForRepeatVisit(date, visitIndex);
}
